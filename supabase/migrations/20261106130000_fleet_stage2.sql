-- Files: one private bucket; the second folder decides which permission applies.
--   <org_id>/work-orders/..., <org_id>/incidents/..., <org_id>/inspections/..., <org_id>/expenses/...

insert into storage.buckets (id, name, public)
values ('fleet-files', 'fleet-files', false)
on conflict (id) do nothing;

create or replace function public.fleet_file_permission(p_name text, p_write boolean)
returns boolean
language sql
stable
security definer
set search_path to 'public'
as $$
  select (storage.foldername(p_name))[1] = public.current_org_id()::text
     and case (storage.foldername(p_name))[2]
           when 'work-orders' then public.has_permission(case when p_write then 'maintenance.write' else 'maintenance.read' end)
           when 'incidents' then public.has_permission(case when p_write then 'incidents.write' else 'incidents.read' end)
           when 'inspections' then public.has_permission(case when p_write then 'inspections.write' else 'inspections.read' end)
           when 'expenses' then public.has_permission(case when p_write then 'costs.write' else 'costs.read' end)
           else false
         end;
$$;

drop policy if exists fleet_files_read on storage.objects;
create policy fleet_files_read on storage.objects for select
  using (bucket_id = 'fleet-files' and (public.fleet_file_permission(name, false) or public.fleet_file_permission(name, true)));

drop policy if exists fleet_files_insert on storage.objects;
create policy fleet_files_insert on storage.objects for insert
  with check (bucket_id = 'fleet-files' and public.fleet_file_permission(name, true));

drop policy if exists fleet_files_update on storage.objects;
create policy fleet_files_update on storage.objects for update
  using (bucket_id = 'fleet-files' and public.fleet_file_permission(name, true));

drop policy if exists fleet_files_delete on storage.objects;
create policy fleet_files_delete on storage.objects for delete
  using (bucket_id = 'fleet-files' and public.fleet_file_permission(name, true));

-- Cost per vehicle and month (roadmap 4.2 TCO): fuel, maintenance, expenses.
create or replace view public.vehicle_monthly_costs
with (security_invoker = true) as
select org_id, vehicle_id, month, category, sum(amount) as amount
  from (
    select org_id, vehicle_id, date_trunc('month', occurred_at)::date as month, 'fuel' as category, total as amount
      from public.fuel_transactions where vehicle_id is not null
    union all
    select org_id, vehicle_id, date_trunc('month', coalesce(closed_at, opened_at))::date, 'maintenance', total_cost
      from public.work_orders where status = 'done'
    union all
    select org_id, vehicle_id, date_trunc('month', occurred_at)::date, category, amount
      from public.vehicle_expenses where vehicle_id is not null
  ) costs
 group by org_id, vehicle_id, month, category;

grant select on public.vehicle_monthly_costs to authenticated;

commit;
