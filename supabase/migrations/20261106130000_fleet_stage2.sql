-- The work order total follows its lines.
create or replace function public.work_order_total()
returns trigger
language plpgsql
security definer
set search_path to 'public'
as $$
declare
  target uuid := coalesce(new.work_order_id, old.work_order_id);
begin
  update public.work_orders
     set total_cost = coalesce((select sum(total) from public.work_order_items where work_order_id = target), 0)
   where id = target;
  if tg_op = 'UPDATE' and old.work_order_id is distinct from new.work_order_id then
    update public.work_orders
       set total_cost = coalesce((select sum(total) from public.work_order_items where work_order_id = old.work_order_id), 0)
     where id = old.work_order_id;
  end if;
  return null;
end;
$$;

drop trigger if exists work_order_items_total on public.work_order_items;
create trigger work_order_items_total after insert or update or delete on public.work_order_items
  for each row execute function public.work_order_total();

