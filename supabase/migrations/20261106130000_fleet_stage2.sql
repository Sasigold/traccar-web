-- Row level security: read / write permission per area, always inside the user's organization.

do $$
declare
  spec text[];
  specs text[][] := array[
    ['vendors', 'maintenance.read', 'maintenance.write'],
    ['work_orders', 'maintenance.read', 'maintenance.write'],
    ['work_order_items', 'maintenance.read', 'maintenance.write'],
    ['issues', 'maintenance.read', 'maintenance.write'],
    ['inspection_templates', 'inspections.read', 'inspections.manage'],
    ['inspection_template_items', 'inspections.read', 'inspections.manage'],
    ['inspections', 'inspections.read', 'inspections.write'],
    ['inspection_items', 'inspections.read', 'inspections.write'],
    ['incidents', 'incidents.read', 'incidents.write'],
    ['incident_photos', 'incidents.read', 'incidents.write'],
    ['incident_parties', 'incidents.read', 'incidents.write'],
    ['insurance_claims', 'incidents.read', 'incidents.write'],
    ['fuel_transactions', 'costs.read', 'costs.write'],
    ['vehicle_expenses', 'costs.read', 'costs.write']
  ];
begin
  foreach spec slice 1 in array specs loop
    execute format('alter table public.%I enable row level security', spec[1]);
    execute format('drop policy if exists %I on public.%I', spec[1] || '_select', spec[1]);
    execute format(
      'create policy %I on public.%I for select using (org_id = public.current_org_id() and (public.has_permission(%L) or public.has_permission(%L)))',
      spec[1] || '_select', spec[1], spec[2], spec[3]);
    execute format('drop policy if exists %I on public.%I', spec[1] || '_write', spec[1]);
    execute format(
      'create policy %I on public.%I for all using (org_id = public.current_org_id() and public.has_permission(%L)) with check (org_id = public.current_org_id() and public.has_permission(%L))',
      spec[1] || '_write', spec[1], spec[3], spec[3]);
    execute format('grant select, insert, update, delete on public.%I to authenticated', spec[1]);
  end loop;
end $$;

