-- 8. Row level security.

do $$
declare
  spec text[];
  specs text[][] := array[
    ['pois', 'poi.read', 'poi.write'],
    ['api_keys', 'integrations.manage', 'integrations.manage'],
    ['webhooks', 'integrations.manage', 'integrations.manage'],
    ['webhook_deliveries', 'integrations.manage', 'integrations.manage']
  ];
begin
  foreach spec slice 1 in array specs loop
    execute format('alter table public.%I enable row level security', spec[1]);
    execute format('drop policy if exists %I on public.%I', spec[1] || '_select', spec[1]);
    execute format(
      'create policy %I on public.%I for select using (org_id = public.current_org_id() and (public.has_permission(%L) or public.has_permission(%L)))',
      spec[1] || '_select', spec[1], spec[2], spec[3]);
    execute format('drop policy if exists %I on public.%I', spec[1] || '_write', spec[1]);
    execute format(
      'create policy %I on public.%I for all using (org_id = public.current_org_id() and public.has_permission(%L)) with check (org_id = public.current_org_id() and public.has_permission(%L))',
      spec[1] || '_write', spec[1], spec[3], spec[3]);
    execute format('grant select, insert, update, delete on public.%I to authenticated', spec[1]);
  end loop;
end $$;

-- Dispatch: a driver sees only their own jobs and may move them along (status, proof).
alter table public.dispatch_jobs enable row level security;

drop policy if exists dispatch_jobs_select on public.dispatch_jobs;
create policy dispatch_jobs_select on public.dispatch_jobs for select
  using (org_id = public.current_org_id()
         and (public.has_permission('dispatch.read') or public.has_permission('dispatch.write'))
         and (not public.is_driver_role() or driver_id = public.my_driver_id()));

drop policy if exists dispatch_jobs_write on public.dispatch_jobs;
create policy dispatch_jobs_write on public.dispatch_jobs for all
  using (org_id = public.current_org_id() and public.has_permission('dispatch.write')
         and not public.is_driver_role())
  with check (org_id = public.current_org_id() and public.has_permission('dispatch.write')
              and not public.is_driver_role());

drop policy if exists dispatch_jobs_driver_update on public.dispatch_jobs;
create policy dispatch_jobs_driver_update on public.dispatch_jobs for update
  using (org_id = public.current_org_id() and public.is_driver_role()
         and driver_id = public.my_driver_id())
  with check (org_id = public.current_org_id() and driver_id = public.my_driver_id()
              and status in ('en_route', 'arrived', 'done', 'failed'));

grant select, insert, update, delete on public.dispatch_jobs to authenticated;

-- 9. Files: proof of delivery under <org_id>/dispatch/... in the fleet-files bucket.

create or replace function public.fleet_file_permission(p_name text, p_write boolean)
returns boolean
language sql
stable
security definer
set search_path to 'public'
as $$
  select (storage.foldername(p_name))[1] = public.current_org_id()::text
     and case (storage.foldername(p_name))[2]
           when 'work-orders' then public.has_permission(case when p_write then 'maintenance.write' else 'maintenance.read' end)
           when 'incidents' then public.has_permission(case when p_write then 'incidents.write' else 'incidents.read' end)
           when 'inspections' then public.has_permission(case when p_write then 'inspections.write' else 'inspections.read' end)
           when 'expenses' then public.has_permission(case when p_write then 'costs.write' else 'costs.read' end)
           when 'safety' then public.has_permission(case when p_write then 'safety.write' else 'safety.read' end)
           when 'dispatch' then public.has_permission('dispatch.read') or public.has_permission('dispatch.write')
           else false
         end;
$$;

