-- Timestamps of the status changes are filled by the database.
create or replace function public.dispatch_job_status()
returns trigger
language plpgsql
set search_path to 'public'
as $$
begin
  if tg_op = 'INSERT' or new.status is distinct from old.status then
    if new.status = 'en_route' and new.started_at is null then
      new.started_at := now();
    elsif new.status = 'arrived' and new.arrived_at is null then
      new.arrived_at := now();
    elsif new.status in ('done', 'failed') and new.completed_at is null then
      new.completed_at := now();
    end if;
    if new.status = 'planned' and (new.vehicle_id is not null or new.driver_id is not null) then
      new.status := 'assigned';
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists dispatch_jobs_status on public.dispatch_jobs;
create trigger dispatch_jobs_status before insert or update on public.dispatch_jobs
  for each row execute function public.dispatch_job_status();

-- 5. API keys: only a SHA-256 hash is stored; the key is shown once when created.

create table if not exists public.api_keys (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references public.organizations (id) on delete cascade,
  name text not null,
  prefix text not null,
  key_hash text not null unique,
  scopes text[] not null default array['read'],
  last_used_at timestamptz,
  expires_at timestamptz,
  revoked_at timestamptz,
  created_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now()
);

-- For the public API gateway (service role only): the organization and scopes of a valid key.
create or replace function public.api_key_lookup(p_key text)
returns table (org_id uuid, scopes text[])
language plpgsql
security definer
set search_path to 'public'
as $$
declare
  found public.api_keys;
begin
  select * into found from public.api_keys k
   where k.key_hash = encode(sha256(convert_to(p_key, 'UTF8')), 'hex')
     and k.revoked_at is null and (k.expires_at is null or k.expires_at > now());
  if found.id is null then
    return;
  end if;
  update public.api_keys set last_used_at = now() where id = found.id;
  return query select found.org_id, found.scopes;
end;
$$;

revoke all on function public.api_key_lookup(text) from public, anon, authenticated;

-- 6. Webhooks: events are queued in webhook_deliveries by triggers and sent by a pg_cron job
--    with an HMAC-SHA256 signature; retries back off exponentially, at most 5 attempts.

create table if not exists public.webhooks (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references public.organizations (id) on delete cascade,
  name text not null,
  url text not null check (url ~ '^https://'),
  events text[] not null default '{}',
  secret text not null default replace(gen_random_uuid()::text || gen_random_uuid()::text, '-', ''),
  active boolean not null default true,
  created_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.webhook_deliveries (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references public.organizations (id) on delete cascade,
  webhook_id uuid not null references public.webhooks (id) on delete cascade,
  event text not null,
  payload jsonb not null,
  status text not null default 'queued' check (status in ('queued', 'sending', 'sent', 'failed')),
  attempts integer not null default 0,
  next_attempt_at timestamptz not null default now(),
  request_id bigint,
  response_code integer,
  error text,
  created_at timestamptz not null default now(),
  sent_at timestamptz
);

create index if not exists webhook_deliveries_due_idx on public.webhook_deliveries (next_attempt_at)
  where status in ('queued', 'sending');

-- Event names: <table>.<insert|update|status>, e.g. dispatch_jobs.status, incidents.insert.
create or replace function public.queue_webhooks()
returns trigger
language plpgsql
security definer
set search_path to 'public'
as $$
declare
  event_name text;
  row_data jsonb := to_jsonb(new);
begin
  if tg_op = 'INSERT' then
    event_name := tg_table_name || '.insert';
  elsif row_data ? 'status' and (to_jsonb(old) ->> 'status') is distinct from (row_data ->> 'status') then
    event_name := tg_table_name || '.status';
  else
    event_name := tg_table_name || '.update';
  end if;
  insert into public.webhook_deliveries (org_id, webhook_id, event, payload)
  select w.org_id, w.id, event_name,
         jsonb_build_object('event', event_name, 'occurred_at', now(), 'data', row_data)
    from public.webhooks w
   where w.active and w.org_id = new.org_id
     and (event_name = any (w.events) or (tg_table_name || '.*') = any (w.events));
  return null;
end;
$$;

do $$
declare
  name text;
begin
  foreach name in array array['dispatch_jobs', 'incidents', 'work_orders', 'issues', 'inspections',
                               'document_alerts', 'driver_violations'] loop
    if to_regclass('public.' || name) is not null then
      execute format('drop trigger if exists %I on public.%I', name || '_webhooks', name);
      execute format('create trigger %I after insert or update on public.%I for each row execute function public.queue_webhooks()',
                     name || '_webhooks', name);
    end if;
  end loop;
end $$;

-- Sender: needs pg_net (bundled with Supabase). Without it deliveries stay queued.
create or replace function public.send_webhooks()
returns integer
language plpgsql
security definer
set search_path to 'public', 'extensions'
as $$
declare
  delivery record;
  body text;
  sent integer := 0;
begin
  if not exists (select 1 from pg_extension where extname = 'pg_net') then
    return 0;
  end if;

  -- Collect answers of the previous run.
  update public.webhook_deliveries d
     set status = case when r.status_code between 200 and 299 then 'sent'
                       when d.attempts >= 5 then 'failed' else 'queued' end,
         response_code = r.status_code,
         error = left(r.error_msg, 500),
         sent_at = case when r.status_code between 200 and 299 then now() end,
         next_attempt_at = now() + make_interval(mins => power(2, d.attempts)::int)
    from net._http_response r
   where d.status = 'sending' and r.id = d.request_id;

  for delivery in
    select d.*, w.url, w.secret from public.webhook_deliveries d
      join public.webhooks w on w.id = d.webhook_id
     where d.status = 'queued' and d.next_attempt_at <= now() and w.active
     order by d.next_attempt_at
     limit 100
     for update of d skip locked
  loop
    body := delivery.payload::text;
    update public.webhook_deliveries
       set status = 'sending',
           attempts = attempts + 1,
           request_id = net.http_post(
             url := delivery.url,
             body := delivery.payload,
             headers := jsonb_build_object(
               'Content-Type', 'application/json',
               'X-ViperFleet-Event', delivery.event,
               'X-ViperFleet-Delivery', delivery.id::text,
               'X-ViperFleet-Signature',
               'sha256=' || encode(hmac(body, delivery.secret, 'sha256'), 'hex')),
             timeout_milliseconds := 10000)
     where id = delivery.id;
    sent := sent + 1;
  end loop;
  return sent;
end;
$$;

revoke all on function public.send_webhooks() from public, anon, authenticated;

select cron.unschedule(jobid) from cron.job where jobname = 'vf_send_webhooks';
select cron.schedule('vf_send_webhooks', '* * * * *', 'select public.send_webhooks()');

