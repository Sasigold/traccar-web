#!/usr/bin/env sh
# One psql script that applies, in order, every migration not yet recorded in
# vf_meta.ui_migrations, and records each one. The same as deploy/migrate.sh (without the backup:
# take one first), for running by hand on the server:
#
#   sh tools/bundle-migrations.sh > docs/owner/apply-migrations.sql
#   docker exec -i <db container> psql -X -v ON_ERROR_STOP=1 -U postgres -d postgres \
#     < docs/owner/apply-migrations.sql
#
# Running it twice is safe: what was applied is skipped. It needs psql (\if, \gset); the Supabase
# Studio SQL editor cannot run it (see docs/owner/CHECKLIST.md for that path).
# LOCAL=1 leaves out "create extension pg_cron" (the local test database has a stand-in).
set -eu
cd "$(dirname "$0")/.."

cat <<'SQL'
-- viper fleet: every migration not applied yet, in order (generated by tools/bundle-migrations.sh).
\set ON_ERROR_STOP 1
create schema if not exists vf_meta;
create table if not exists vf_meta.ui_migrations (
  name text primary key,
  applied_at timestamptz not null default now()
);
revoke all on schema vf_meta from public;
SQL

for file in supabase/migrations/*.sql; do
  name=$(basename "$file")
  printf "\n-- ─── %s\n" "$name"
  printf "select exists (select 1 from vf_meta.ui_migrations where name = '%s') as vf_done \\\\gset\n" "$name"
  printf "\\\\if :vf_done\n\\\\echo 'Already applied: %s'\n\\\\else\n\\\\echo 'Applying: %s'\n" "$name" "$name"
  if [ "${LOCAL:-}" = 1 ]; then
    grep -v '^create extension if not exists pg_cron;' "$file"
  else
    cat "$file"
  fi
  printf "\ninsert into vf_meta.ui_migrations (name) values ('%s') on conflict do nothing;\n\\\\endif\n" "$name"
done

cat <<'SQL'

-- PostgREST only sees new tables after a schema reload.
notify pgrst, 'reload schema';
\echo 'Migrations done.'
SQL
