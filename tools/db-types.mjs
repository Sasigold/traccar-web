// ARC-11: writes src/common/fleet/database.d.ts, the fleet database's tables, views, enums and
// functions as the `Database` type that @supabase/supabase-js understands, from the JSON that
// tools/db-types.sql prints. Run through tools/db-types.sh (needs a database with every
// migration applied, as supabase/tests/run.sh makes); CI fails when the committed file is stale.
//
//   node tools/db-types.mjs schema.json > src/common/fleet/database.d.ts
import { readFileSync } from 'node:fs';

const { columns, enums, functions } = JSON.parse(readFileSync(process.argv[2], 'utf8'));

const SCALARS = {
  bool: 'boolean',
  int2: 'number',
  int4: 'number',
  int8: 'number',
  float4: 'number',
  float8: 'number',
  numeric: 'number',
  json: 'Json',
  jsonb: 'Json',
};

const enumType = (name) =>
  enums[name] ? enums[name].map((label) => JSON.stringify(label)).join(' | ') : null;

const scalar = (udt) => SCALARS[udt] ?? enumType(udt) ?? 'string';

const columnType = (column) =>
  column.type === 'ARRAY' ? `(${scalar(column.udt.slice(1))})[]` : scalar(column.udt);

// format_type() names, for function arguments and results.
const FORMATTED = {
  boolean: 'boolean',
  smallint: 'number',
  integer: 'number',
  bigint: 'number',
  real: 'number',
  'double precision': 'number',
  numeric: 'number',
  json: 'Json',
  jsonb: 'Json',
  void: 'undefined',
  record: 'Json',
};
const formattedType = (name) => {
  if (name.endsWith('[]')) return `(${formattedType(name.slice(0, -2))})[]`;
  return FORMATTED[name] ?? enumType(name) ?? 'string';
};

const key = (name) => (/^[a-z_][a-z0-9_]*$/i.test(name) ? name : JSON.stringify(name));

const relations = {};
columns.forEach((column) => {
  (relations[column.table] ||= { kind: column.kind, columns: [] }).columns.push(column);
});

const indent = (text, depth) =>
  text
    .split('\n')
    .map((line) => (line ? '  '.repeat(depth) + line : line))
    .join('\n');

const block = (entries) => (entries.length ? `{\n${entries.join('\n')}\n}` : '{}');

const rowOf = (list) =>
  block(list.map((c) => `  ${key(c.column)}: ${columnType(c)}${c.nullable ? ' | null' : ''}`));
const insertOf = (list) =>
  block(
    list
      .filter((c) => !c.generated)
      .map(
        (c) =>
          `  ${key(c.column)}${c.nullable || c.default ? '?' : ''}: ${columnType(c)}${c.nullable ? ' | null' : ''}`,
      ),
  );
const updateOf = (list) =>
  block(
    list
      .filter((c) => !c.generated)
      .map((c) => `  ${key(c.column)}?: ${columnType(c)}${c.nullable ? ' | null' : ''}`),
  );

const tables = Object.entries(relations)
  .filter(([, relation]) => relation.kind === 'BASE TABLE')
  .map(
    ([name, { columns: list }]) =>
      `${key(name)}: {\n  Row: ${rowOf(list).replace(/\n/g, '\n  ')}\n  Insert: ${insertOf(list).replace(/\n/g, '\n  ')}\n  Update: ${updateOf(list).replace(/\n/g, '\n  ')}\n  Relationships: []\n}`,
  );
const views = Object.entries(relations)
  .filter(([, relation]) => relation.kind === 'VIEW')
  .map(
    ([name, { columns: list }]) =>
      `${key(name)}: {\n  Row: ${rowOf(list.map((c) => ({ ...c, nullable: true }))).replace(/\n/g, '\n  ')}\n  Relationships: []\n}`,
  );

// Overloads (same name, other arguments) become a union, as supabase gen types does.
const byName = {};
functions.forEach((fn) => (byName[fn.name] ||= []).push(fn));
const fnEntries = Object.entries(byName).map(([name, list]) => {
  const variants = list.map((fn) => {
    const args = fn.args.filter((arg) => arg.name);
    const argsType = args.length
      ? block(
          args.map(
            (arg) => `  ${key(arg.name)}${arg.optional ? '?' : ''}: ${formattedType(arg.type)}`,
          ),
        )
      : 'Record<PropertyKey, never>';
    const result = formattedType(fn.returns);
    return `{\n  Args: ${argsType.replace(/\n/g, '\n  ')}\n  Returns: ${fn.set ? `(${result})[]` : result}\n}`;
  });
  return `${key(name)}: ${variants.join(' | ')}`;
});
const enumEntries = Object.keys(enums)
  .sort()
  .map((name) => `${key(name)}: ${enumType(name)}`);

const section = (entries) => indent(block(entries), 0).replace(/\n/g, '\n      ');

process.stdout
  .write(`// Generated by tools/db-types.sh from the migrations (ARC-11). Do not edit by hand:
// change a migration, then run \`sh tools/db-types.sh\`. Tables that only exist on the server
// (vehicles, drivers, profiles, documents...) come from supabase/tests/base_standin.sql, so their
// columns are the ones the stand-in has.

export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];

export type Database = {
  public: {
    Tables: ${section(tables)}
    Views: ${section(views)}
    Functions: ${section(fnEntries)}
    Enums: ${section(enumEntries)}
    CompositeTypes: Record<PropertyKey, never>;
  };
};

type PublicSchema = Database['public'];
export type Tables<T extends keyof PublicSchema['Tables']> = PublicSchema['Tables'][T]['Row'];
export type TablesInsert<T extends keyof PublicSchema['Tables']> =
  PublicSchema['Tables'][T]['Insert'];
export type TablesUpdate<T extends keyof PublicSchema['Tables']> =
  PublicSchema['Tables'][T]['Update'];
export type Views<T extends keyof PublicSchema['Views']> = PublicSchema['Views'][T]['Row'];
export type Enums<T extends keyof PublicSchema['Enums']> = PublicSchema['Enums'][T];
`);
